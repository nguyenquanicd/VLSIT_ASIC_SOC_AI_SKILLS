"""Look up and fetch protocol documents of reference/md_doc and reference/org_doc.

Purpose : lets the assistant read one section of a standard instead of a whole file (saves tokens), search
          the standards, keep reference/md_doc/vlsit_INDEX.md current, and download a source document only after
          the user approved that exact file.
Actions :
  index                       rebuild md_doc/vlsit_INDEX.md from the YAML headers of the Markdown files
  list                        one line per document: file, protocol, revision, licence, redistribution
  toc DOC                     headings of one document with line numbers
  section DOC TEXT [--max N]  print the first section whose heading contains TEXT (default 120 lines)
  search TERM [--doc DOC]     case-insensitive search; prints file:line: text (at most 40 hits)
  fetch URL OUT [--yes]       without --yes: report size and type only and exit 4 (ask the user first);
                              with --yes: download to OUT (refuses to overwrite)
Exit    : 0 success, 1 error, 4 download not approved yet.
Standard library only; text is read and written as UTF-8.
Examples:
  vlsit_protocol_docs.py list
  vlsit_protocol_docs.py section tilelink_ul_opentitan_tlul "Usage of Opcode"
  vlsit_protocol_docs.py fetch https://example.org/spec.md org_doc/spec.md
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MD_DIR = ROOT / "reference" / "md_doc"
UA = {"User-Agent": "vlsit-asic-ip-microspec/1.0"}


def header(path):
    text = path.read_text(encoding="utf-8")
    meta = {}
    if text.startswith("---"):
        for line in text.split("---", 2)[1].splitlines():
            m = re.match(r'(\w+):\s*"?(.*?)"?\s*$', line)
            if m:
                meta[m.group(1)] = m.group(2)
    return meta


def docs():
    return sorted(p for p in MD_DIR.glob("*.md") if p.name != "vlsit_INDEX.md")


def find_doc(name):
    for p in docs():
        if p.stem == name or p.name == name:
            return p
    matches = [p for p in docs() if name.lower() in p.stem.lower()]
    if len(matches) == 1:
        return matches[0]
    raise SystemExit("ERROR: document '%s' not found or ambiguous; run: list" % name)


def action_list(_a):
    for p in docs():
        h = header(p)
        print("%s | %s | %s | %s | redistribution=%s" % (p.stem, h.get("protocol", "?"), h.get("revision", "?"),
                                                      h.get("license", "?"), h.get("redistribution", "?")))
    if not docs():
        print("no documents in %s" % MD_DIR)
    return 0


def action_index(_a):
    rows = ["# Protocol document index", "",
            "Generated by `scripts/vlsit_protocol_docs.py index`. Read a document with `vlsit_protocol_docs.py section`.", "",
            "| File | Protocol | Revision | Licence | Redistribution | Retrieved |", "|---|---|---|---|---|---|"]
    for p in docs():
        h = header(p)
        rows.append("| %s | %s | %s | %s | %s | %s |" % (p.name, h.get("protocol", "?"), h.get("revision", "?"),
                                                       h.get("license", "?"), h.get("redistribution", "?"), h.get("retrieved", "?")))
    (MD_DIR / "vlsit_INDEX.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("OK: wrote %s (%d documents)" % (MD_DIR / "vlsit_INDEX.md", len(docs())))
    return 0


def headings(lines):
    in_code = False
    for i, line in enumerate(lines):
        if line.startswith("```"):
            in_code = not in_code
        m = re.match(r"(#{1,6})\s+(.*)", line)
        if m and not in_code:
            yield i, len(m.group(1)), m.group(2).strip()


def action_toc(a):
    lines = find_doc(a.doc).read_text(encoding="utf-8").splitlines()
    for i, level, title in headings(lines):
        print("%5d %s%s" % (i + 1, "  " * (level - 1), title))
    return 0


def action_section(a):
    path = find_doc(a.doc)
    lines = path.read_text(encoding="utf-8").splitlines()
    heads = list(headings(lines))
    for n, (i, level, title) in enumerate(heads):
        if a.text.lower() in title.lower():
            end = len(lines)
            for j, lv, _ in heads[n + 1:]:
                if lv <= level:
                    end = j
                    break
            chunk = lines[i:end]
            print("%s lines %d-%d" % (path.name, i + 1, end))
            print("\n".join(chunk[:a.max]))
            if len(chunk) > a.max:
                print("... %d more lines; raise --max" % (len(chunk) - a.max))
            return 0
    print("ERROR: no heading contains '%s' in %s; run: toc" % (a.text, path.name))
    return 1


def action_search(a):
    files = [find_doc(a.doc)] if a.doc else docs()
    hits = 0
    for p in files:
        for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            if a.term.lower() in line.lower():
                print("%s:%d: %s" % (p.stem, n, line.strip()[:160]))
                hits += 1
                if hits >= 40:
                    print("... stopped at 40 hits; narrow with --doc")
                    return 0
    if not hits:
        print("no match")
    return 0


def action_fetch(a):
    out = Path(a.out)
    if out.exists():
        print("ERROR: %s already exists" % out)
        return 1
    try:
        req = urllib.request.Request(a.url, headers=UA, method="HEAD")
        with urllib.request.urlopen(req, timeout=30) as r:
            size, kind = r.headers.get("Content-Length", "unknown"), r.headers.get("Content-Type", "unknown")
    except Exception as exc:  # network and HTTP errors differ widely; report them in one line
        print("ERROR: cannot reach %s: %s" % (a.url, exc))
        return 1
    if not a.yes:
        print("APPROVAL NEEDED: %s -> %s, size %s bytes, type %s. Ask the user, then rerun with --yes." % (a.url, out, size, kind))
        return 4
    out.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(urllib.request.Request(a.url, headers=UA), timeout=120) as r:
        data = r.read()
    out.write_bytes(data)
    print("OK: wrote %s (%d bytes)" % (out, len(data)))
    return 0


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("index")
    sub.add_parser("list")
    t = sub.add_parser("toc")
    t.add_argument("doc")
    s = sub.add_parser("section")
    s.add_argument("doc")
    s.add_argument("text")
    s.add_argument("--max", type=int, default=120)
    q = sub.add_parser("search")
    q.add_argument("term")
    q.add_argument("--doc")
    f = sub.add_parser("fetch")
    f.add_argument("url")
    f.add_argument("out")
    f.add_argument("--yes", action="store_true", help="the user approved this exact download")
    a = parser.parse_args()
    return {"index": action_index, "list": action_list, "toc": action_toc, "section": action_section,
            "search": action_search, "fetch": action_fetch}[a.action](a)


if __name__ == "__main__":
    sys.exit(main())
